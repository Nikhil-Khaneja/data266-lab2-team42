import io
import json
import os

import imagehash
from datasets import load_dataset
from PIL import Image

SEED = 266
DATASET_NAME = "lambdalabs/naruto-blip-captions"
TARGET_SIZE = (512, 512)

DATASET_DESCRIPTION = """Naruto BLIP Captions: {} images of Naruto anime character art, each
with a short BLIP-generated caption describing the scene. Limitations: (1) captions are
auto-generated by BLIP, so they are sometimes generic or miss specific character names;
(2) the dataset over-represents a small set of recurring characters and poses, so styles
and compositions less common in the source material are under-represented."""


def is_valid_image(example):
    try:
        img = example["image"]
        if not isinstance(img, Image.Image):
            img = Image.open(io.BytesIO(img))
        img.convert("RGB")
        return True
    except Exception:
        return False


def compute_phash(example):
    img = example["image"]
    if not isinstance(img, Image.Image):
        img = Image.open(io.BytesIO(img))
    return str(imagehash.phash(img))


def remove_corrupted_and_duplicates(dataset):
    total_before = len(dataset)

    valid_mask = [is_valid_image(ex) for ex in dataset]
    dataset = dataset.select([i for i, ok in enumerate(valid_mask) if ok])
    corrupted_removed = total_before - len(dataset)

    seen_hashes = set()
    keep_indices = []
    for i, ex in enumerate(dataset):
        h = compute_phash(ex)
        if h in seen_hashes:
            continue
        seen_hashes.add(h)
        keep_indices.append(i)
    dataset = dataset.select(keep_indices)
    duplicates_removed = (total_before - corrupted_removed) - len(dataset)

    return dataset, corrupted_removed, duplicates_removed


def resize_image(example):
    img = example["image"]
    if not isinstance(img, Image.Image):
        img = Image.open(io.BytesIO(img))
    example["image"] = img.convert("RGB").resize(TARGET_SIZE)
    return example


def save_as_imagefolder(dataset, split_dir):
    os.makedirs(split_dir, exist_ok=True)
    metadata_path = os.path.join(split_dir, "metadata.jsonl")
    with open(metadata_path, "w", encoding="utf-8") as metadata_file:
        for i, example in enumerate(dataset):
            file_name = "{:05d}.jpg".format(i)
            example["image"].save(os.path.join(split_dir, file_name))
            metadata_file.write(json.dumps({"file_name": file_name, "text": example["text"]}) + "\n")


def prepare_dataset(output_dir):
    os.makedirs(output_dir, exist_ok=True)
    dataset = load_dataset(DATASET_NAME, split="train")

    dataset, corrupted_removed, duplicates_removed = remove_corrupted_and_duplicates(dataset)
    dataset = dataset.map(resize_image)

    split = dataset.train_test_split(test_size=0.10, seed=SEED)
    train_set = split["train"]
    test_set = split["test"]

    save_as_imagefolder(train_set, os.path.join(output_dir, "train"))
    save_as_imagefolder(test_set, os.path.join(output_dir, "test"))

    report = {
        "total_before_cleaning": corrupted_removed + duplicates_removed + len(dataset),
        "corrupted_removed": corrupted_removed,
        "duplicates_removed": duplicates_removed,
        "train_size": len(train_set),
        "test_size": len(test_set),
        "description": DATASET_DESCRIPTION.format(corrupted_removed + duplicates_removed + len(dataset)),
    }
    return report


if __name__ == "__main__":
    report = prepare_dataset("data/processed/part2")
    print(json.dumps(report, indent=2))
